// ANEMnistNative.kt — Apple-platform actual implementation via cinterop
// Calls the C bridge (ANEMnist.h) which wraps ObjC ANE runtime.
package com.ane.mnist

import anemnist.*          // generated by cinterop from ANEMnist.h
import kotlinx.cinterop.*

@OptIn(ExperimentalForeignApi::class)
actual class MnistTrainer actual constructor(config: MnistConfig) {

    private val handle: CPointer<ANEMnistTrainer>

    init {
        val cCfg = cValue<ANEMnistConfig> {
            input_dim = config.inputDim
            hidden_dim = config.hiddenDim
            output_dim = config.outputDim
            batch_size = config.batchSize
            learning_rate = config.learningRate
            momentum = config.momentum
            accum_steps = config.accumSteps
            max_compiles = config.maxCompiles
        }
        handle = memScoped {
            ane_mnist_create(cCfg.ptr)
        } ?: error("Failed to create ANE MNIST trainer")
    }

    actual fun loadData(dataDir: String): Boolean {
        val rc = ane_mnist_load_data(
            handle,
            "$dataDir/train-images-idx3-ubyte",
            "$dataDir/train-labels-idx1-ubyte",
            "$dataDir/t10k-images-idx3-ubyte",
            "$dataDir/t10k-labels-idx1-ubyte",
        )
        return rc == 0
    }

    actual fun compile(): Boolean {
        return ane_mnist_compile(handle) == 0
    }

    actual fun trainStep(): TrainStepResult {
        val r = ane_mnist_train_step(handle)
        return TrainStepResult(
            loss = r.loss,
            accuracy = r.accuracy,
            step = r.step,
            epoch = r.epoch,
            epochDone = r.epoch_done,
            compileCount = r.compile_count,
            budgetExhausted = r.budget_exhausted,
        )
    }

    actual fun evaluate(): Float {
        return ane_mnist_evaluate(handle)
    }

    actual val batchesPerEpoch: Int
        get() = ane_mnist_batches_per_epoch(handle)

    actual val trainCount: Int
        get() = ane_mnist_train_count(handle)

    actual val testCount: Int
        get() = ane_mnist_test_count(handle)

    actual val currentStep: Int
        get() = ane_mnist_current_step(handle)

    actual fun close() {
        ane_mnist_free(handle)
    }
}
